import { test, expect } from "@playwright/test";

test("accurate prepared draft preserves mixed selection order, required flags and partial-day inputs", async ({ page }) => {
  await page.goto("/plan/new?destination=da-lat");
  await expect(page.locator('[aria-label="Chọn điểm ghé"] input[type="checkbox"]')).toHaveCount(30);
  await page.getByLabel("Ngày bắt đầu").fill("2026-11-10");
  await page.getByLabel("Ngày kết thúc").fill("2026-11-10");
  await page.getByLabel("Giờ đến", { exact: true }).fill("17:00");
  await page.getByLabel("Giờ rời đi", { exact: true }).fill("19:00");
  await page.getByLabel("Tên nơi lưu trú hoặc điểm gốc").fill("Nhà của nhóm");
  await page.getByLabel("Vĩ độ điểm gốc").fill("11.94");
  await page.getByLabel("Kinh độ điểm gốc").fill("108.44");
  await page.getByLabel("Tổng ngân sách").fill("");
  await page.getByLabel("Tên điểm nhập tay").fill("Điểm riêng");
  await page.getByLabel("Vĩ độ", { exact: true }).fill("11.95");
  await page.getByLabel("Kinh độ", { exact: true }).fill("108.45");
  await page.getByRole("button", { name: "Thêm điểm nhập tay" }).click();
  await page.getByLabel("Tìm trong catalog").fill("Vườn hoa thành phố");
  await page.getByRole("checkbox", { name: /^Vườn hoa thành phố Đà Lạt/ }).check();
  await page.getByLabel("Bắt buộc Vườn hoa thành phố Đà Lạt", { exact: true }).check();
  await page.getByLabel("Tôi tự lên kế hoạch").check();
  await page.getByRole("button", { name: "Xem kết quả chuẩn bị" }).click();
  const review = page.getByRole("region", { name: "Thông tin đã kiểm tra" });
  await expect(review).toBeVisible();
  await expect(review.locator("ol li")).toHaveText(["Điểm riêng · tùy chọn", "Vườn hoa thành phố Đà Lạt · bắt buộc"]);
  await expect(review).toContainText("17:00 → 2026-11-10 · 19:00");
  await expect(review).toContainText("Điểm gốc tạm");
  await expect(page.getByText("Chưa đặt ngân sách", { exact: true })).toBeVisible();
  await page.getByLabel("Tổng ngân sách").fill("0");
  await expect(review).toHaveCount(0);
  await page.getByRole("button", { name: "Xem kết quả chuẩn bị" }).click();
  await expect(review.locator("ol li")).toHaveCount(2);
  await page.getByLabel("Giờ đến", { exact: true }).fill("20:00");
  await page.getByRole("button", { name: "Xem kết quả chuẩn bị" }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("giờ đến/rời");
  await expect(review).toHaveCount(0);
  await expect(page.getByRole("list", { name: "Các điểm đã thêm" }).getByRole("listitem")).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
